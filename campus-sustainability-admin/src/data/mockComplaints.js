// FR-5: priority derived from a configurable category rule (kept as a
// simple lookup table here; swap for a real config screen later).
export const PRIORITY_RULES = {
  Safety: 'High',
  Energy: 'High',
  Water: 'Medium',
  Infrastructure: 'Medium',
  Waste: 'Low',
}

export const PRIORITY_META = {
  High: { label: 'High', color: '#a3402f', bg: '#f7e6e1' },
  Medium: { label: 'Medium', color: '#b45309', bg: '#fef3c7' },
  Low: { label: 'Low', color: '#3f5a4a', bg: '#e3efe6' },
}

export function computePriority(category) {
  return PRIORITY_RULES[category] || 'Medium'
}

// FR-6: unique token generated when a complaint is verified.
export function generateToken(id) {
  const suffix = Math.random().toString(36).slice(2, 6).toUpperCase()
  return `TKN-${id}-${suffix}`
}

const now = new Date('2026-07-26T09:00:00')
function hoursFromNow(h) {
  return new Date(now.getTime() + h * 3600 * 1000).toISOString()
}

